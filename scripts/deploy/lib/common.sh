#!/usr/bin/env bash
# Shared deployment contract. The live k8s/cvp-platform.yaml is the source for
# resource identities; service-local manifests are historical references.
CVP_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../../.." && pwd)"
CVP_NAMESPACE="${CVP_NAMESPACE:-cvp}"
CVP_CONTEXT="${CVP_CONTEXT:-docker-desktop}"
CVP_TIMEOUT="${CVP_TIMEOUT:-600s}"
CVP_LOCAL_OVERLAY="$CVP_ROOT/k8s/overlays/local"
# Git Bash otherwise rewrites Linux paths passed through kubectl exec on Windows.
export MSYS_NO_PATHCONV=1

cvp_log() { printf '[cvp] %s\n' "$*"; }
cvp_die() { printf '[cvp] ERROR: %s\n' "$*" >&2; exit 1; }
cvp_require() { command -v "$1" >/dev/null 2>&1 || cvp_die "Required command missing: $1"; }

cvp_preflight() {
  cvp_require kubectl
  [[ "$CVP_NAMESPACE" == cvp ]] || cvp_die "This deployment is scoped to namespace cvp"
  local context
  context="$(kubectl config current-context)"
  [[ "$context" == "$CVP_CONTEXT" ]] || cvp_die "Expected Kubernetes context $CVP_CONTEXT; found $context"
  kubectl get namespace "$CVP_NAMESPACE" >/dev/null || cvp_die "Namespace $CVP_NAMESPACE is missing"
  kubectl get secret cvp-database-credentials -n "$CVP_NAMESPACE" >/dev/null || cvp_die 'Existing cvp-database-credentials Secret is required; credentials are never generated by these scripts'
}

cvp_service_dir() {
  case "$1" in
    ai-assistant|appointment|maintenance-reminder|partner-mock|inventory|mcp-server|telemetry) printf '%s/k8s/base/%s\n' "$CVP_ROOT" "$1" ;;
    *) cvp_die "Unknown service: $1" ;;
  esac
}

cvp_deployment() {
  case "$1" in
    ai-assistant) printf 'ai-assistant-service\n' ;;
    appointment) printf 'appointment-service\n' ;;
    maintenance-reminder) printf 'maintenance-reminder-service\n' ;;
    partner-mock) printf 'partner-integration-mock\n' ;;
    inventory) printf 'inventory-service\n' ;;
    mcp-server) printf 'mcp-server\n' ;;
    telemetry) printf 'telemetry-service\n' ;;
    *) cvp_die "Unknown service: $1" ;;
  esac
}

cvp_image() {
  local name image
  name="$(cvp_image_name "$1")"
  if [[ -n "${CVP_IMAGE_TAG:-}" ]]; then
    cvp_validate_tag "$CVP_IMAGE_TAG"
    printf '%s:%s\n' "$name" "$CVP_IMAGE_TAG"
    return
  fi
  cvp_live_image "$1"
}

cvp_live_image() {
  local name deployment image
  name="$(cvp_image_name "$1")"
  deployment="$(cvp_deployment "$1")"
  image="$(kubectl get "deployment/$deployment" -n "$CVP_NAMESPACE" -o jsonpath='{.spec.template.spec.containers[0].image}')"
  [[ "$image" == "$name:"* ]] || cvp_die "Unexpected live image for $deployment: $image"
  cvp_validate_tag "${image##*:}"
  printf '%s\n' "$image"
}

cvp_image_name() {
  case "$1" in
    ai-assistant) printf 'docker.io/library/cvp-ai-assistant-service\n' ;;
    appointment) printf 'docker.io/library/cvp-appointment-service\n' ;;
    maintenance-reminder) printf 'docker.io/library/cvp-maintenance-reminder-service\n' ;;
    partner-mock) printf 'docker.io/library/cvp-partner-integration-mock\n' ;;
    inventory) printf 'docker.io/library/cvp-inventory-service\n' ;;
    mcp-server) printf 'docker.io/library/cvp-mcp-server\n' ;;
    telemetry) printf 'docker.io/library/cvp-telemetry-service\n' ;;
    *) cvp_die "Unknown service: $1" ;;
  esac
}

cvp_validate_tag() {
  [[ "$1" =~ ^[A-Za-z0-9_][A-Za-z0-9_.-]{0,127}$ ]] || cvp_die "Invalid Docker image tag: $1"
}

cvp_services=(ai-assistant appointment maintenance-reminder partner-mock inventory mcp-server telemetry)

# A build tag is selected once by the entry point and exported to subprocesses.
# Refuse existing local and currently deployed tags before any build starts.
cvp_select_build_tag() {
  local requested="${1:-}" candidate service image collision attempt
  cvp_require docker
  if [[ -n "$requested" ]]; then
    cvp_validate_tag "$requested"
    candidate="$requested"
  else
    for attempt in {1..10}; do
      candidate="$(date -u +%Y%m%d-%H%M%S)"
      collision=false
      for service in "${@:2}"; do
        image="$(cvp_image_name "$service"):$candidate"
        if docker image inspect "$image" >/dev/null 2>&1 ||
           [[ "$(kubectl get "deployment/$(cvp_deployment "$service")" -n "$CVP_NAMESPACE" -o jsonpath='{.spec.template.spec.containers[0].image}')" == "$image" ]]; then
          collision=true
          break
        fi
      done
      [[ "$collision" == false ]] && break
      sleep 1
    done
    [[ "$collision" == false ]] || cvp_die 'Could not find an unused UTC timestamp tag'
  fi
  for service in "${@:2}"; do
    image="$(cvp_image_name "$service"):$candidate"
    docker image inspect "$image" >/dev/null 2>&1 && cvp_die "Refusing to overwrite local image $image"
    [[ "$(kubectl get "deployment/$(cvp_deployment "$service")" -n "$CVP_NAMESPACE" -o jsonpath='{.spec.template.spec.containers[0].image}')" != "$image" ]] || cvp_die "Refusing to overwrite deployed image $image"
  done
  CVP_IMAGE_TAG="$candidate"
  export CVP_IMAGE_TAG
}

# An ephemeral child Kustomization applies image replacements without changing base YAML.
cvp_make_render() {
  local source="$1" service image name tag
  CVP_RENDER_DIR="$(mktemp -d "$(dirname "$source")/.cvp-render-XXXXXXXX")"
  {
    printf 'apiVersion: kustomize.config.k8s.io/v1beta1\nkind: Kustomization\nresources:\n  - ../%s\nimages:\n' "$(basename "$source")"
    for service in "${@:2}"; do
      image="$(cvp_image "$service")"
      name="$(cvp_image_name "$service")"
      tag="${image##*:}"
      printf '  - name: %s\n    newName: %s\n    newTag: %s\n' "$name" "$name" "$tag"
    done
  } > "$CVP_RENDER_DIR/kustomization.yaml"
  if ! kubectl kustomize "$CVP_RENDER_DIR" >/dev/null; then
    cvp_remove_render
    cvp_die 'Dynamic Kustomize render failed'
  fi
}

cvp_remove_render() {
  if [[ -n "${CVP_RENDER_DIR:-}" ]]; then
    [[ "$CVP_RENDER_DIR" == "$CVP_ROOT/k8s/"*"/.cvp-render-"* ]] || cvp_die 'Refusing to remove an unexpected render path'
    rm -rf -- "$CVP_RENDER_DIR"
    CVP_RENDER_DIR=''
  fi
}

cvp_assert_image() {
  local service="$1" expected="$2" deployment actual ready_pods
  deployment="$(cvp_deployment "$service")"
  actual="$(kubectl get "deployment/$deployment" -n "$CVP_NAMESPACE" -o jsonpath='{.spec.template.spec.containers[0].image}')"
  [[ "$actual" == "$expected" ]] || cvp_die "Unexpected Deployment image for $deployment: $actual (expected $expected)"
  ready_pods="$(kubectl get pod -n "$CVP_NAMESPACE" -l "app=$deployment" -o jsonpath='{range .items[*]}{.status.containerStatuses[0].ready}{"|"}{.spec.containers[0].image}{"\n"}{end}')"
  grep -Fxq "true|$expected" <<< "$ready_pods" || cvp_die "No Ready Pod uses $expected for $deployment"
}

cvp_source_dir() {
  case "$1" in
    partner-mock) printf '%s/cvp-partner-integration-mock\n' "$CVP_ROOT" ;;
    mcp-server) printf '%s/cvp-mcp-server\n' "$CVP_ROOT" ;;
    *) printf '%s/cvp-%s-service\n' "$CVP_ROOT" "$1" ;;
  esac
}

cvp_render() {
  kubectl kustomize "$1" >/dev/null || cvp_die "Kustomize render failed: $1"
}

cvp_wait_service() {
  local name="$1" endpoint
  kubectl rollout status "deployment/$name" -n "$CVP_NAMESPACE" --timeout="$CVP_TIMEOUT"
  kubectl get "service/$name" -n "$CVP_NAMESPACE" >/dev/null
  endpoint="$(kubectl get endpointslice -n "$CVP_NAMESPACE" -l "kubernetes.io/service-name=$name" -o jsonpath='{.items[0].endpoints[0].conditions.ready}')"
  [[ "$endpoint" == true ]] || cvp_die "Service $name has no Ready endpoint"
}
